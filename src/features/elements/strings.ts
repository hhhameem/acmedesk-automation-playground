const DICTS: Record<Locale, Dict> = { en, de, ar };

export type ElT = (key: ElKey, vars?: Record<string, string | number>) => string;

/** Translator for the Element Lab. `{name}` placeholders are filled from `vars`. */
export function useElT(): { t: ElT; locale: Locale } {
  const locale = useUIStore((s) => s.locale);
  const dict = DICTS[locale] ?? en;
  const t: ElT = (key, vars) => {
    const text = dict[key] ?? en[key];
    return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => String(vars[name] ?? m)) : text;
  };
  return { t, locale };
}
